import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { connect } from './helpers/sidecar.js';

test('unified vault: lock, password rotation, cross-account restore, deduplication and concurrent writes', {skip: !process.env.TOOLBOX_SIDECAR, timeout: 120000}, async t => {
  const root = await fs.mkdtemp(path.resolve('backend/target/vault-test-'));
  const sourceDir = path.join(root, 'source'), targetDir = path.join(root, 'target');
  const hosts = [];
  const open = async dir => {
    const scoped = path.join(dir,'io.github.aili0617.toolbox');
    await fs.mkdir(scoped,{recursive:true}); await fs.writeFile(path.join(scoped,'.legacy-migration-v1.done'),'test-only');
    const host = connect(process.env.TOOLBOX_SIDECAR, {...process.env, DBX_PLUGIN_DATA_DIR: dir});
    hosts.push(host); await host.invoke('plugin/initialize', {host:{protocolVersions:[1]}}); return host;
  };
  t.after(async () => { await Promise.all(hosts.map(h => h.close())); await fs.rm(root, {recursive:true,force:true}); });
  const source = await open(sourceDir);
  const call = (method, params = {}) => source.invoke(`toolbox/${method}`, params);
  await call('keys/setup', {password:'source-password'});
  const key = await call('keys/create', {name:'example', algorithm:'aes-256', generate:true});
  const account = await call('totp/save', {name:'account', note:'Test note', issuer:'Example', account:'user', secret:'jbsw y3dp ehpk3pxp', digits:6, period:30, algorithm:'SHA256'});
  assert.doesNotMatch(JSON.stringify(account), /JBSWY3DPEHPK3PXP/);
  assert.equal((await call('keys/list')).keys.length, 1);
  assert.equal((await call('totp/list')).entries.length, 1);
  const originalBackup = await fs.readFile(path.join(sourceDir,'io.github.aili0617.toolbox','keystore'));
  const generated = await call('totp/generate', {id:account.entry.id});
  assert.match(generated.windows[1].code, /^\d{6}$/);
  await call('totp/lock');
  assert.equal((await call('keys/status')).unlocked, false);
  await assert.rejects(call('totp/generate', {id:account.entry.id}));
  // Manual codes remain usable without persisting or unlocking an account.
  assert.match((await call('totp/manual', {secret:'JBSWY3DPEHPK3PXP'})).windows[1].code, /^\d{6}$/);
  await call('keys/unlock', {password:'source-password'});
  await call('keys/lock');
  assert.equal((await call('totp/status')).unlocked, false);
  await assert.rejects(call('totp/reveal', {id:account.entry.id}));
  await call('keys/unlock', {password:'source-password'});
  await call('keys/change-password', {currentPassword:'source-password', newPassword:'rotated-password'});
  await call('keys/lock');
  await assert.rejects(call('keys/unlock', {password:'source-password'}));
  await call('keys/unlock', {password:'rotated-password'});
  assert.equal((await call('totp/list')).entries[0].note, 'Test note');
  assert.match((await call('totp/generate', {id:account.entry.id})).windows[1].code, /^\d{6}$/);
  assert.equal((await call('keys/list')).keys[0].id, key.key.id);
  const backup = await fs.readFile(path.join(sourceDir,'io.github.aili0617.toolbox','keystore'));
  assert.ok(!backup.includes(Buffer.from('JBSWY3DPEHPK3PXP')));
  const target = await open(targetDir);
  const rpc = (method, params = {}) => target.invoke(`toolbox/${method}`,params);
  await rpc('keys/setup',{password:'target-password'});
  const preview = async (bytes=backup, password='rotated-password') => {
    await rpc('keys/restore/begin');
    await rpc('keys/restore/upload',{data:bytes.toString('base64')});
    return rpc('keys/restore/preview',{password});
  };
  await assert.rejects(preview(backup,'wrong-password'));
  const corrupt = Buffer.from(backup); corrupt[corrupt.length-1] ^= 1;
  await assert.rejects(preview(corrupt));
  assert.equal((await rpc('totp/list')).entries.length,0);
  let result = await preview();
  assert.deepEqual([result.addedKeys,result.addedTotp,result.duplicates],[1,1,0]);
  assert.doesNotMatch(JSON.stringify(result), /JBSWY|material|secret/);
  await rpc('keys/restore/commit',{token:result.token});
  assert.equal((await rpc('totp/list')).entries[0].note,'Test note');
  await assert.rejects(preview(originalBackup,'rotated-password'));
  result = await preview(originalBackup,'source-password');
  assert.deepEqual([result.addedKeys,result.addedTotp,result.duplicates],[0,0,2]);
  await rpc('keys/lock');
  await rpc('keys/unlock',{password:'target-password'});
  await assert.rejects(rpc('keys/restore/commit',{token:result.token}));
  result = await preview();
  await rpc('totp/save',{id:(await rpc('totp/list')).entries[0].id,name:'Changed',issuer:'Example',account:'user'});
  await assert.rejects(rpc('keys/restore/commit',{token:result.token}));
  // Another Sidecar must not overwrite a newer snapshot.
  const other = await open(targetDir);
  await other.invoke('toolbox/keys/unlock',{password:'target-password'});
  const entry=(await rpc('totp/list')).entries[0];
  await rpc('totp/save',{id:entry.id,name:'Latest',issuer:'Example',account:'user'});
  await assert.rejects(other.invoke('toolbox/totp/save',{id:entry.id,name:'Stale',issuer:'Example',account:'user'}),/VAULT_CHANGED/);
  assert.equal((await rpc('totp/list')).entries[0].name,'Latest');
});
